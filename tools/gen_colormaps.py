#!/usr/bin/env python3
"""Regenerate src/avbd_viz/colormap_data.inc (256-entry sRGB tables) from matplotlib."""
import os
import matplotlib

NAMES = ["viridis", "turbo", "coolwarm", "plasma", "magma", "inferno",
         "cividis", "RdBu_r", "twilight", "jet", "gray"]

out = os.path.join(os.path.dirname(__file__), "..", "src", "avbd_viz", "colormap_data.inc")
with open(out, "w") as f:
    f.write("// Generated by tools/gen_colormaps.py from matplotlib %s. Do not edit.\n"
            % matplotlib.__version__)
    f.write("static constexpr int kColormapCount = %d;\n" % len(NAMES))
    f.write("static const char* const kColormapNames[kColormapCount] = {%s};\n"
            % ", ".join('"%s"' % n for n in NAMES))
    f.write("static const unsigned char kColormapTable[kColormapCount][256][3] = {\n")
    for n in NAMES:
        cmap = matplotlib.colormaps[n]
        rows = []
        for i in range(256):
            r, g, b, _ = cmap(i / 255.0)
            rows.append("{%d,%d,%d}" % (round(r * 255), round(g * 255), round(b * 255)))
        f.write("  { // %s\n" % n)
        for k in range(0, 256, 8):
            f.write("    " + ",".join(rows[k:k + 8]) + ",\n")
        f.write("  },\n")
    f.write("};\n")
print("wrote", os.path.normpath(out))
